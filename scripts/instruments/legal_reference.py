def transcription_completeness() -> dict:
    """Transcribed vs declared, per Order, and which are unverified.

    Reported rather than silently trusted. A published determination of
    "outside" rests on the transcription being COMPLETE, and completeness is a
    different claim from correctness: every entry present can be right while an
    absent one turns a Scheduled Area into a denial.
    """
    counts: dict = {}
    for entry in SCHEDULED_DISTRICTS:
        order = entry[2]
        counts[order] = counts.get(order, 0) + 1
    out = {}
    for key in SCHEDULED_AREA_ORDERS:
        declared = ORDER_DECLARED_AREA_COUNTS.get(key)
        out[key] = {
            "number": SCHEDULED_AREA_ORDERS[key].get("number"),
            "transcribed": counts.get(key, 0),
            "declared": declared,
            "verified": declared is not None,
            "agrees": None if declared is None else declared == counts.get(key, 0),
        }
    return out

