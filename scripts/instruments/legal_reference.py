# legal position is usually that the territory stays scheduled - but "usually"
# is not a determination, and this panel exists precisely to stop a plausible
# inference being rendered as a legal fact. Successor districts are therefore
# recorded as NOT DETERMINED with a note naming the parent, which tells a reader
# exactly which Order to go and read.
