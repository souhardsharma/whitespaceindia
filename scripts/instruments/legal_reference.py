def order_enumerates_districts(order_key: str) -> bool:
    """Whether absence from this Order's text means a district is not scheduled.

    Only meaningful for an Order that lists districts. One that schedules by
    village - naming individual settlements across a gazette - says nothing
    about a district it happens not to mention, so silence there is a gap and
    not a negative.
    """
    return (SCHEDULED_AREA_ORDERS[order_key].get("district_coverage")
            != "below_district")


