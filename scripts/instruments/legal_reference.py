def build_determinations() -> tuple[dict[str, dict], list[str], dict]:
    """Resolve every curated district name to a Census 2011 code.

    A name that does not resolve is a build failure, not a silent miss. An
    unresolved entry would simply never match at render time and the district
    would show "not determined" - indistinguishable from a genuine gap, which is
    exactly the kind of quiet wrongness this instrument is built to avoid.
    """
    import os
    import sys as _sys
    _sys.path.insert(0, str(Path(__file__).resolve().parent))
    from district_resolution import Gazetteer, normalize_name

    # The gazetteer only supplies the census code for a state/district name, so
    # the committed districts.json serves as well as the source DBF and needs no
    # fetch cache. Without this fallback the legal table could only be rebuilt on
    # a machine that had already downloaded 150 MB of Census tables, which meant
    # a one-line correction to an Order's wording was a half-hour job.
    dbf = os.environ.get("INSTRUMENTS_GEO_DBF")
    if not dbf and os.environ.get("INSTRUMENTS_CACHE_DIR"):
        candidate = Path(os.environ["INSTRUMENTS_CACHE_DIR"]) / "geo" / "2011_Dist.dbf"
        dbf = str(candidate) if candidate.exists() else None
    gaz = Gazetteer(Path(dbf)) if dbf else Gazetteer.from_published()

    index: dict[tuple[str, str], dict] = {}
    for row in gaz.rows:
        index[(normalize_name(row["ST_NM"]), normalize_name(row["DISTRICT"]))] = row

    out: dict[str, dict] = {}
    problems: list[str] = []

    def lookup(state: str, district: str) -> dict | None:
        return index.get((normalize_name(state), normalize_name(district)))

    for state, district, order_key, coverage, detail in SCHEDULED_DISTRICTS:
        row = lookup(state, district)
        if row is None:
            problems.append(f"SCHEDULED_DISTRICTS: {state} / {district} not in the Census 2011 gazetteer")
            continue
        order = SCHEDULED_AREA_ORDERS[order_key]
        out[str(int(row["censuscode"]))] = {
            "status": "within" if coverage == "full" else "partial",
            "instrument": order["title"],
            "provision": f'{order["number"]}, notified {order["notified"]}',
            "citation": order["gazette"] + (f'. Covers: {detail}.' if detail else ""),
            "sourceUrl": order["source_url"],
            "lastReviewed": reviewed_for(state),
            # boundary_basis is a NOUN PHRASE ("territorial divisions as
            # existing at 20 February 2003"), not a sentence. It has to be
            # embedded in one. Emitting it bare put a mid-sentence fragment at
            # the head of 83 of the 171 determinations, on screen and in the
            # exported PDF alike.
            "note": (
                f'The Order fixes the area by reference to {order["boundary_basis"]}. '
                + ("It names this district as a whole."
                   if coverage == "full"
                   else "It names only part of this district, so district-level "
                        "status cannot settle whether a particular site is inside it.")
            ),
        }

    parent_coverage = {(normalize_name(st), normalize_name(d)): cov
                       for st, d, _, cov, _ in SCHEDULED_DISTRICTS}
    for state, district, parent, order_key, outcome, how in SUCCESSOR_DISTRICTS:
        row = lookup(state, district)
        if row is None:
            problems.append(f"SUCCESSOR_DISTRICTS: {state} / {district} not in the gazetteer")
            continue
        if outcome not in ("within", "partial", "outside"):
            problems.append(f"SUCCESSOR_DISTRICTS: {district} has outcome {outcome!r}")
            continue
        order = SCHEDULED_AREA_ORDERS[order_key]
        # `within` rests on the parent being named WHOLLY. Checked here, so a
        # parent later corrected to partial cannot leave a child asserting it.
        if outcome == "within":
            parents = [cov for (st, d), cov in parent_coverage.items()
                       if st == normalize_name(state)
                       and d in {normalize_name(parent),
                                 normalize_name("Dakshin Bastar Dantewada")
                                 if parent == "Dantewara" else ""}]
            if "full" not in parents:
                problems.append(
                    f"SUCCESSOR_DISTRICTS: {district} is `within` but its parent "
                    f"{parent} is not transcribed as named wholly")
        basis = (f"This district was {how}. {order['number']} fixes its area by "
                 f"reference to {order['boundary_basis']}, and a district drawn "
                 "later does not change the ground the Order scheduled.")
        if outcome == "within":
            note = (basis + f" On that date every part of this district lay "
                    f"within {parent}, which the Order names as a whole, so "
                    "every part of it is a Scheduled Area. The Ministry of "
                    "Panchayati Raj lists this district among notified Fifth "
                    "Schedule Areas.")
        elif outcome == "partial":
            note = (basis + f" The Order names part of {parent}, and part of "
                    "what it names now lies in this district, so district-level "
                    "status cannot settle whether a particular site is inside "
                    "it. The Ministry of Panchayati Raj lists this district "
                    "among notified Fifth Schedule Areas.")
        else:
            note = (basis + " No part of the ground the Order scheduled passed to "
                    "this district, so no part of it is a Scheduled Area under "
                    "that Order. The Ministry of Panchayati Raj's list of "
                    "notified Fifth Schedule Areas does not name it either.")
        out[str(int(row["censuscode"]))] = {
            "status": outcome,
            "instrument": order["title"],
            "provision": f'{order["number"]}, notified {order["notified"]}',
            "citation": order["gazette"],
            "sourceUrl": order["source_url"],
            "lastReviewed": REVIEWED_2026_09_25,
            "successorOf": parent,
            "note": note,
        }

    for state, order in UNTRANSCRIBED_STATES.items():
        if normalize_name(state) not in {st for st, _ in index}:
            # A rule that applies to no row is indistinguishable from one that
            # was quietly dropped, so it is reported - unless it is a case we
            # have named and justified. Telangana was constituted in 2014, so
            # no Census 2011 district carries its name and none ever will; its
            # districts appear under Andhra Pradesh, which has its own entry.
            if state not in NO_CENSUS_2011_ROWS:
                problems.append(
                    f"UNTRANSCRIBED_STATES: {state!r} matches no Census 2011 "
                    f"state, so its rule applied to nothing. Add it to "
                    f"NO_CENSUS_2011_ROWS with a reason, or fix the spelling.")
            continue
        for (st_norm, _), row in index.items():
            if st_norm != normalize_name(state):
                continue
            code = str(int(row["censuscode"]))
            if code in out:
                continue
            out[code] = {
                "status": "not_determined",
                "instrument": f"Governed by {order}",
                "lastReviewed": REVIEWED,
                "note": (
                    f"{state} has Fifth Schedule Scheduled Areas, declared by "
                    f"{order}. That Order has not yet been transcribed into this "
                    "reference, so no district in this state carries a "
                    "determination. Read the Order itself before relying on any "
                    "answer for this state."
                ),
            }

    for state in SIXTH_SCHEDULE_STATES:
        areas = SIXTH_SCHEDULE_AREAS.get(state, {})
        whole = state in SIXTH_SCHEDULE_WHOLE_STATE
        for (st_norm, dist_norm), row in index.items():
            if st_norm != normalize_name(state):
                continue
            code = str(int(row["censuscode"]))
            if code in out:
                continue
            council = None
            if whole:
                # A BARE NOUN PHRASE. The sentence below already supplies
                # ", under the Sixth Schedule (Articles 244(2) and 275(1))",
                # so naming the Schedule here too published "lies within an
                # Autonomous District Council under the Sixth Schedule, under
                # the Sixth Schedule (Articles 244(2) and 275(1))" on 7
                # Meghalaya and 4 Tripura district pages. Every other value
                # this variable takes is a bare name - "the Karbi Anglong
                # Autonomous Council" - and this one has to match them.
                council = "an Autonomous District Council"
            else:
                for name, body in areas.items():
                    if normalize_name(name) == dist_norm:
                        council = body
                        break
            # SETTLED, not unknown. Article 244(1) applies the Fifth Schedule
            # "in any State other than the States of Assam, Meghalaya, Tripura
            # and Mizoram", so a district here cannot be a Fifth Schedule
            # Scheduled Area. Publishing that as "not determined" left the
            # largest determinable block in the country reading as a gap - the
            # exact thing this phase exists to remove.
            out[code] = {
                "status": "outside",
                "instrument": "Constitution of India, Article 244(1)",
                "provision": "Article 244(1)",
                "lastReviewed": REVIEWED,
                "note": (
                    f"Article 244(1) applies the Fifth Schedule in every State "
                    f"other than Assam, Meghalaya, Tripura and Mizoram, so no "
                    f"part of {state} is a Fifth Schedule Scheduled Area and "
                    f"PESA does not apply here."
                    + (f" A different protection does: this district lies "
                       f"within {council}, under the Sixth Schedule "
                       f"(Articles 244(2) and 275(1)), which has its own "
                       f"consent and land-transfer safeguards."
                       if council else
                       " The Sixth Schedule reaches other districts of this "
                       "State through Autonomous District Councils, but not "
                       "this one.")
                ),
            }

    # ── Sub-divisions an Order names WHOLLY, resolved to Census units ───
    #
    # A district named only in part cannot settle where a particular site is.
    # Where the Order names a whole tehsil, taluka or block, it CAN - for a
    # site in that sub-division. The names are transcribed, not parsed, and
    # only an unambiguous single match is published: a name that matches no
    # Census sub-district, or more than one, is recorded as unmatched and
    # changes nothing. This can only raise a site to `within`; it never lowers
    # one to `outside`, because a sub-division the Order does not name may
    # still contain scheduled land under a unit this reference cannot see.
    sub_index: dict[int, dict] = {}
    # Also by STATE, because a district has often been split since its Order.
    # Shahdol's Pushparajgarh, Anuppur, Jaithari and Kotma sit in Anuppur
    # district, created in 2003; Gujarat's Vyara and Songadh in Tapi, created
    # 2007; Dediapada and Sagbara in Narmada, 1997. Those tehsils are still
    # scheduled - the Order named them and no Order has unnamed them - they
    # have simply moved. Searching only the district the Order names loses
    # them, and losing them is indistinguishable from their not existing.
    state_index: dict[str, dict] = {}
    sub_district_of: dict[int, int] = {}
    sub_parents: dict[int, list[int]] = {}
    try:
        subs = json.loads(
            (OUT.parent / "subdistricts.json").read_text(encoding="utf-8"))
        for code, rec in (subs.get("subdistricts") or subs).items():
            key = normalize_name(rec.get("name") or "")
            if not key:
                continue
            # EVERY district it lies in, not just the first. 31 tehsils
            # straddle a district boundary and are published once; indexing
            # only one parent means an Order naming that tehsil in the OTHER
            # district finds nothing, and finding nothing is published as
            # "the Order does not name this district" - the strongest negative
            # claim this instrument makes.
            parents = rec.get("districts") or (
                [rec["district"]] if rec.get("district") is not None else [])
            for dt in parents:
                sub_index.setdefault(int(dt), {}).setdefault(
                    key, []).append(int(rec["code"]))
            state_index.setdefault(
                normalize_name(rec.get("state_name") or ""), {}).setdefault(
                key, []).append(int(rec["code"]))
            if parents:
                sub_district_of[int(rec["code"])] = int(parents[0])
                sub_parents[int(rec["code"])] = [int(x) for x in parents]
    except Exception as exc:  # noqa: BLE001
        problems.append(f"subdistricts.json unreadable ({type(exc).__name__}), "
                        f"so no partial district can be resolved by sub-division")

    unused_regimes = {normalize_name(k) for k in OTHER_REGIMES}
    matched_units = unmatched_units = 0
    for (state, district), names in WHOLLY_NAMED_SUBDIVISIONS.items():
        row = lookup(state, district)
        if row is None:
            problems.append(
                f"WHOLLY_NAMED_SUBDIVISIONS: {state} / {district} not in the gazetteer")
            continue
        code = str(int(row["censuscode"]))
        entry = out.get(code)
        if entry is None or entry.get("status") != "partial":
            problems.append(
                f"WHOLLY_NAMED_SUBDIVISIONS: {state} / {district} is "
                f"{entry.get('status') if entry else 'absent'}, not partial")
            continue
        pool = sub_index.get(int(row["censuscode"]), {})
        statewide = state_index.get(normalize_name(state), {})
        codes, unmatched, elsewhere = [], [], []
        for name in names:
            # BOTH sides of an alias are normalised. Index keys are normalised
            # (spaces and punctuation stripped), so an un-normalised target
            # such as "chhota udaipur" could never equal "chhotaudaipur", and
            # every multi-word alias silently matched nothing; and a key with a
            # space ("deogarh baria") never equalled the normalised name it was
            # looked up by.
            aliases = {normalize_name(k): v for k, v in SUBDIVISION_ALIASES.items()}
            key = normalize_name(aliases.get(normalize_name(name), name))
            hits = pool.get(key) or []
            if len(hits) == 1:
                codes.append(hits[0])
                matched_units += 1
                continue
            # Not in the district the Order names. Look across the State: the
            # district may have been split since, and a tehsil that moved is
            # still the tehsil the Order scheduled.
            wide = statewide.get(key) or []
            if len(wide) == 1:
                codes.append(wide[0])
                matched_units += 1
                elsewhere.append(name)
                continue
            # Genuinely not identified: a spelling this reference does not
            # know, or a unit the Census frame does not carry at all.
            unmatched.append(name)
            unmatched_units += 1
        # Only units that lie in THIS district. A unit the Order names under
        # this district that now lies in a successor is listed by name in
        # foundInSuccessorDistrict and is scheduled through the successor's own
        # entry; keeping its code here told any reader of the field that
        # Ganjam contains R. Udayagiri, which is in Gajapati.
        own = int(row["censuscode"])
        entry["scheduledSubdistricts"] = sorted(
            c for c in codes if sub_district_of.get(c) == own
            or own in (sub_parents.get(c) or []))
        entry["namedWholly"] = list(names)
        if unmatched:
            # NOT the same as `foundInSuccessorDistrict`. One says the Census
            # frame does not carry this unit under any name we know; the other
            # says it does, in a district created after the Order. Merging them
            # made a reorganisation look like a transcription failure.
            entry["unmatchedNames"] = unmatched
        if elsewhere:
            entry["foundInSuccessorDistrict"] = elsewhere
        entry["subdivisionNote"] = (
            "The Order names these sub-divisions of this district in whole. A "
            "site inside one of them is inside the Scheduled Area; a site "
            "elsewhere in the district is not settled by this, because the "
            "Order may reach it through a unit - a revenue circle, a "
            "panchayat, a village - that the Census sub-district frame does "
            "not carry. The match is by NAME against Census 2011 "
            "sub-districts, and a Census sub-district is not the same "
            "administrative unit in every State: a tehsil in Madhya Pradesh, "
            "a taluka in Gujarat and Maharashtra, a tahsil or police station "
            "in Odisha, a community development block in parts of the east. "
            "Where the Order's unit and the Census unit share a name they are "
            "usually the same ground, but the identity is a name match and is "
            "published as one."
        )

    # ── Everything the Orders do not reach, said affirmatively ──────────
    #
    # Up to here the table held 171 of 640 districts and the other 469 were
    # simply absent - rendered as "not determined", which is what a district
    # under an Order nobody has transcribed also reads as. Those are different
    # facts: one is a gap in this reference, the other is a determination that
    # nothing schedules the place. Leaving them identical made 73% of the
    # country an unanswered question when most of it has a clear answer.
    transcribed = {normalize_name(st) for st, _, _, _, _ in SCHEDULED_DISTRICTS}
    sixth = {normalize_name(x) for x in SIXTH_SCHEDULE_STATES}
    fifth = {normalize_name(x) for x in FIFTH_SCHEDULE_STATES}
    other_regimes = {normalize_name(k): v for k, v in OTHER_REGIMES.items()}
    state_name_of = {}
    for (st_norm, _), row in index.items():
        state_name_of.setdefault(st_norm, row["ST_NM"])

    for (st_norm, _), row in index.items():
        code = str(int(row["censuscode"]))
        if code in out:
            continue
        state = state_name_of[st_norm]

        orders_here = sorted({k for st, _, k, _, _ in SCHEDULED_DISTRICTS
                              if normalize_name(st) == st_norm})
        if st_norm in transcribed and not all(
                order_enumerates_districts(k) for k in orders_here):
            # The Order for this State works below district level, so its
            # silence about this district is not a finding that nothing here
            # is scheduled.
            titles = "; ".join(SCHEDULED_AREA_ORDERS[k]["title"]
                               for k in orders_here)
            out[code] = {
                "status": "not_determined",
                "instrument": titles,
                "lastReviewed": REVIEWED,
                "note": (
                    f"The Presidential Order for {state} schedules areas below "
                    "district level - by taluka and by individual village - and "
                    "names no district as a whole. It does not name this "
                    "district in the list transcribed here, but that list is a "
                    "State compilation rather than the Order's own text, so its "
                    "silence cannot settle whether a village in this district "
                    "is scheduled. Read the Order."
                ),
            }
        elif st_norm in transcribed:
            # The Order declares which areas in its State ARE Scheduled Areas.
            # A district it does not name is therefore not one - on the face of
            # the Order, as transcribed here and reviewed on the date below.
            orders = sorted({SCHEDULED_AREA_ORDERS[k]["title"]
                             for st, _, k, _, _ in SCHEDULED_DISTRICTS
                             if normalize_name(st) == st_norm})
            out[code] = {
                "status": "outside",
                "instrument": "; ".join(orders),
                "lastReviewed": reviewed_for(state),
                "note": (
                    (f"The Presidential Order for {state} declares which areas "
                     "in the State are Scheduled Areas. It does not name this "
                     "district, in whole or in part, so no part of it is a "
                     "Scheduled Area under that Order."
                     if len(orders) == 1 else
                     f"Two Presidential Orders declare the Scheduled Areas in "
                     f"what was {state} in 2011 - {' and '.join(orders)}. The "
                     "districts they reach - as the first Order's text names "
                     "them, as the Andhra Pradesh High Court recited them in "
                     "Gundla Venkateswara Rao (1983), and as the Ministry of "
                     "Panchayati Raj lists notified Fifth Schedule Areas - do "
                     "not include this one, so no part of it is a Scheduled "
                     "Area under them.")
                    + " A later Order could add one; this reference states the "
                    f"position as transcribed and reviewed on {reviewed_for(state)}."
                ),
            }
        elif st_norm in sixth or st_norm in fifth:
            # Handled above: Sixth Schedule, or a Fifth Schedule State whose
            # Order is not yet transcribed. Never reached, but explicit so a
            # future State added to one of those lists cannot fall through to
            # the affirmative branch below.
            continue
        else:
            regime = other_regimes.get(st_norm)
            unused_regimes.discard(st_norm)
            out[code] = {
                "status": "outside",
                "instrument": FIFTH_SCHEDULE_SOURCE,
                "sourceUrl": FIFTH_SCHEDULE_URL,
                "lastReviewed": REVIEWED,
                "note": (
                    f"No Presidential Order under paragraph 6 of the Fifth "
                    f"Schedule declares any Scheduled Area in {state}, so no "
                    "part of this district is one and PESA does not apply."
                    + (f" A different protection does apply here: {regime}."
                       if regime else "")
                ),
            }

    # Withdraw the negative where a second official source disagrees with the
    # Order as transcribed. Only ever a downgrade to `not_determined`: this
    # must never manufacture a Scheduled Area, because a summary table is not
    # the instrument that declares one.
    for code, (dname, sname, because) in NAMED_BY_MOPR_NOT_BY_ORDER.items():
        cur = out.get(code)
        if not cur or cur.get("status") != "outside":
            continue
        out[code] = {
            "status": "not_determined",
            "instrument": cur.get("instrument"),
            "sourceUrl": cur.get("sourceUrl"),
            "lastReviewed": REVIEWED,
            "note": (
                f"The Presidential Order for {sname} as transcribed here does "
                f"not name {dname}, but {because}. Those two cannot both be "
                "current, and this reference does not hold whatever reached "
                "the district after the Order. The position is therefore "
                "recorded as undetermined rather than as a denial: consent "
                "may well be a legal precondition here, and it should be "
                "checked against the Order in force before anything is "
                "concluded from this page."
            ),
        }

    for st_norm in sorted(unused_regimes):
        problems.append(
            f"OTHER_REGIMES: {st_norm!r} matched no district, so the "
            f"protection it records reached nobody. A spelling that drifts "
            f"from the Census frame takes the note with it silently.")

    # Published, not just counted. The header promises these figures and they
    # were computed and dropped, so a reader could see 75 resolved units with
    # no way to tell how many the Orders name in the first place.
    coverage = {
        "districtsPartial": sum(1 for d in out.values()
                                if d.get("status") == "partial"),
        "districtsTranscribed": len(WHOLLY_NAMED_SUBDIVISIONS),
        "unitsNamed": matched_units + unmatched_units,
        "unitsResolved": matched_units,
        "unitsUnresolved": unmatched_units,
    }

    return out, problems, coverage


def main() -> None:
    determinations, problems, coverage = build_determinations()
    if problems:
        print("FAILED: curated district names that do not resolve:")
        for p in problems:
            print("  -", p)
        raise SystemExit(1)

    by_status: dict[str, int] = {}
    for d in determinations.values():
        by_status[d["status"]] = by_status.get(d["status"], 0) + 1

    # The latest review of anything in the reference, not the first.
    latest = max([REVIEWED]
                 + [d.get("lastReviewed") or REVIEWED for d in determinations.values()]
                 + [o.get("last_reviewed") or REVIEWED for o in OBLIGATIONS])
    payload = {
        "last_reviewed": latest,
        # How much of the partial-district wording has been transcribed and
        # resolved. Computed and then dropped before, so a reader could see
        # the resolved units with no way to tell what they are a fraction of.
        "subdivision_coverage": coverage,
        "obligations": [
            {
                "instrument": o["instrument"],
                "provision": o["provision"],
                "requirement": o["requirement"],
                "trigger": o["trigger"],
                "triggerKey": o["trigger_key"],
                "kind": o["kind"],
                "sourceUrl": o["source_url"],
                "lastReviewed": o["last_reviewed"],
                "verified": o["verified"],
                "note": o.get("note"),
            }
            for o in OBLIGATIONS
        ],
        "determinations": determinations,
        "notes": NOTES,
        "counts": {
            "obligations": len(OBLIGATIONS),
            "verified": sum(1 for o in OBLIGATIONS if o["verified"]),
            "determinations": len(determinations),
            "determinations_by_status": by_status,
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  {len(OBLIGATIONS)} obligations, "
          f"{sum(1 for o in OBLIGATIONS if o['verified'])} verified")
    print(f"  {len(determinations)} Scheduled Area determinations: {by_status}")


if __name__ == "__main__":
    main()


# HOW MANY AREAS EACH ORDER DECLARES, against how many are transcribed below.
#
# Nothing recorded this, so a transcription that DROPS an item was undetectable
# by construction: the entry simply did not exist, the district fell through to
# the affirmative-negative branch, and it was published as "the Order does not
# name this district, in whole or in part, so no part of it is a Scheduled
# Area" - the strongest negative claim this instrument makes, on an omission.
# An acceptance reviewer reported exactly that for Jharkhand/Garhwa, alleging
# C.O. 229 names "Garhwa District - Bhandaria Block" as item 14 of 15 while 14
# entries are transcribed. That allegation is NOT resolved here: every official
# source for these Orders is an image-only scan, so the claim could be neither
# confirmed nor refuted from this repository, and inventing a Scheduled Area is
# as harmful as omitting one - it would tell a proponent and a Gram Sabha that
# consent is a precondition when it may not be.
#
# What IS fixed is the blindness. `declares` is the number of areas the Order's
# own schedule lists, read from the Order. Where it is None, the transcription
# has NOT been checked for completeness against the source and the suite says
# so out loud instead of implying coverage it cannot demonstrate.
#
# Filling one in requires the gazette text, not a secondary compendium: MoTA's
# own compendium is already known to be out of date on C.O. 114 (see above).
