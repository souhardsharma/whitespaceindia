/**
 * Per-entity pages are never ISR, and proposal pages are never rendered at all.
 *
 * An ISR render is a write to Vercel's cache in 8 KB units, HTML and RSC
 * payload alike. Proposal pages were ISR, and a crawl of the register ran the
 * month's writes to 1.5 million against the Hobby plan's 200,000. Rendered
 * per request instead, the next crawls ran origin transfer to 30 GB against
 * 10 GB and the account was paused. They are now one static page assembled
 * in the browser. This fails if a dynamic-segment page opts back into ISR, or
 * if proposals go back to a server render.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

function pages(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return pages(path);
    return name === "page.tsx" ? [path] : [];
  });
}

test("no page under a dynamic segment is regenerated by ISR", () => {
  const offenders = pages("app")
    .filter((file) => /\[[^\]]+\]/.test(file))
    .filter((file) => {
      const src = readFileSync(file, "utf8");
      const isr = /export const revalidate\s*=\s*(?!false)/.test(src);
      const onDemand = !/export const dynamicParams\s*=\s*false/.test(src);
      return isr && onDemand;
    });
  assert.deepEqual(offenders, []);
});

test("proposal pages are one static page, never a server render", () => {
  assert.ok(!existsSync(join("app", "instruments", "consent", "[proposalId]")),
    "a dynamic proposal route renders ~92,000 pages on demand");
  const shell = readFileSync(join("app", "instruments", "consent", "view", "page.tsx"), "utf8");
  assert.doesNotMatch(shell, /export const (dynamic|revalidate)/);
  assert.doesNotMatch(shell, /lib\/instruments\/server/);
  const view = readFileSync(join("components", "instruments", "ProposalView.tsx"), "utf8");
  assert.match(view, /^"use client";/);
  const config = readFileSync("next.config.mjs", "utf8");
  assert.match(config, /source: "\/instruments\/consent\/:proposalId\(\\\\d\{1,12\}\)", destination: "\/instruments\/consent\/view"/);
});
