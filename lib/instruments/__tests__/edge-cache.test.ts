/**
 * Per-entity pages are cached at Vercel's edge, never by ISR.
 *
 * An ISR render is a write to Vercel's cache in 8 KB units, HTML and RSC
 * payload alike. Proposal pages were ISR, and a crawl of the register ran the
 * month's writes to 1.5 million against the Hobby plan's 200,000. They now
 * render per request and next.config.mjs keeps the answer at the edge for a
 * day. This fails if a dynamic-segment page opts back into ISR, or if the
 * proposal page loses its edge cache.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

function pages(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return pages(path);
    return name === "page.tsx" ? [path] : [];
  });
}

test("no page under a dynamic segment is regenerated by ISR", () => {
  const offenders = pages("app")
    .filter((file) => /\[[^\]]+\]/.test(file))
    .filter((file) => {
      const src = readFileSync(file, "utf8");
      const isr = /export const revalidate\s*=\s*(?!false)/.test(src);
      const onDemand = !/export const dynamicParams\s*=\s*false/.test(src);
      return isr && onDemand;
    });
  assert.deepEqual(offenders, []);
});

test("proposal pages render per request and are kept at the edge", () => {
  const page = readFileSync(join("app", "instruments", "consent", "[proposalId]", "page.tsx"), "utf8");
  assert.match(page, /export const dynamic = "force-dynamic"/);
  const config = readFileSync("next.config.mjs", "utf8");
  assert.match(config, /"\/instruments\/consent\/:proposalId\(\\\\d\{1,12\}\)"/);
  assert.match(config, /Vercel-CDN-Cache-Control/);
});
